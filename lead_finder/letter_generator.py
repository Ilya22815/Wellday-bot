IT_INDUSTRIES = {
    "Информационные технологии", "IT", "Разработка программного обеспечения",
    "Телекоммуникации", "Интернет", "Кибербезопасность",
}
FINANCE_INDUSTRIES = {
    "Банки", "Страхование", "Финансы", "Инвестиции",
}


def generate_letter(company):
    name = company.get("name", "вашей компании")
    industries = set(company.get("industries", []))

    if industries & IT_INDUSTRIES:
        template = IT_LETTER
    elif industries & FINANCE_INDUSTRIES:
        template = FINANCE_LETTER
    else:
        template = DEFAULT_LETTER

    return template.format(name=name)
